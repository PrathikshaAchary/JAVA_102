package com;

public class Employee {
      private int id;
      private String name;
      private double sal;
      private String des;
	  public int getId() {
		  return id;
	  }
	  public void setId(int id) {
		  this.id = id;
	  }
	  public String getName() {
		  return name;
	  }
	  public void setName(String name) {
		  this.name = name;
	  }
	  public double getSal() {
		  return sal;
	  }
	  public void setSal(double sal) {
		  this.sal = sal;
	  }
	  public String getDes() {
		  return des;
	  }
	  public void setDes(String des) {
		  this.des = des;
	  }
}
